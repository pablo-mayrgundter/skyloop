"""Build a standalone static site from the four infographic pages.

The page sources are claude.ai artifact fragments (no doctype/head/body, links to
each other by artifact URL). This wraps each one in a full HTML document, moves
its <title>/<style>/<link> into <head>, and rewrites the artifact links to the
sibling files here, so the site works from any static host (GitHub Pages, a
local file server). Run from the repo root:  python site/build.py
"""
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "site"

PAGES = [  # (source, output, artifact URL, preview folder)
    ("overview/index.html", "index.html",
     "https://claude.ai/artifact/E75ZQx2eW1CXWKeJgPk6gi", "overview/preview"),
    ("boom-shield/infographic/index.html", "boomshield.html",
     "https://claude.ai/artifact/1GASTWSYperFtVLyLY29VJ", "boom-shield/infographic/preview"),
    ("skyloop-review/infographic/index.html", "skyloop.html",
     "https://claude.ai/artifact/Rvmp18jJLdP7pAPWvuiHHK", "skyloop-review/infographic/preview"),
    ("hyperloop/infographic/index.html", "hyperloop.html",
     "https://claude.ai/artifact/QbRskhNLJEzpye6SzGC3fB", "hyperloop/infographic/preview"),
]

SKELETON = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<!-- Generated by site/build.py from {src}; edit the source, not this file. -->
{head}
</head>
<body>
{body}
</body>
</html>
"""


def build_page(src, url_map):
    text = (ROOT / src).read_text(encoding="utf-8")
    split = text.index('<div class="wrap">')
    head, body = text[:split], text[split:]
    head = re.sub(r'<meta name="claude:[^"]*"[^>]*>\n?', "", head).strip()
    for url, local in url_map.items():
        # sibling pages open in the same tab on the static site
        body = body.replace(f'href="{url}" target="_blank" rel="noopener"', f'href="{local}"')
        body = body.replace(url, local)
    return SKELETON.format(src=src, head=head, body=body.strip())


def main():
    url_map = {url: out for _, out, url, _ in PAGES}
    assets = OUT / "assets"
    assets.mkdir(parents=True, exist_ok=True)
    for src, out, _, preview in PAGES:
        (OUT / out).write_text(build_page(src, url_map), encoding="utf-8")
        stem = "overview" if out == "index.html" else Path(out).stem
        for png in sorted((ROOT / preview).glob("*.png")):
            shutil.copyfile(png, assets / f"{stem}-{png.name}")
        print(f"{src} -> site/{out}")


if __name__ == "__main__":
    main()
